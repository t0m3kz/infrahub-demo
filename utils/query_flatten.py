"""Flatten a GraphQL query for the Infrahub server: fragments written out in place, the meaning unchanged.

The server's cost of a query document grows with its fragment use, not with its size or depth: the same 2,546 fields
take 3.4 s reached through five levels of fragments and 0.13 s written out, and a device-config query with fragments
takes nearly as long for a device that does not exist (no data read) as for a real one. So the registered queries are
the flattened form of the source files under ``queries/``, which keep their fragments for the people who edit them.

A fragment spread is an inline fragment with the fragment's type condition, so writing it out changes nothing. One
shape is kept as a fragment: an inline fragment directly inside another inline fragment of the operation, which the
server's query analyzer refuses with HTTP 500 (``infrahub_sdk.utils.extract_fields`` reads ``.name`` off it). There
the inner block becomes a fragment used exactly once, whose body may nest freely (the analyzer does not walk fragment
bodies). No schema is needed and every type condition is kept, so the server answers exactly what it answered before.

The registered copies live in ``queries/flat/`` under the source's relative path and are written by
``uv run invoke flatten-queries``: run it after editing a query or a fragment, the server runs only the copies.

Server version: proven on Infrahub 1.12 (the version ``uv.lock`` runs), where every copy answers byte for byte what its
source answers. On 1.11.11 a fragment spread inside an inline fragment returns nulls for the fragment's fields (and a
type condition nested two levels deep loses its fields too), so the copies need 1.12.
"""

from __future__ import annotations

from pathlib import Path

from graphql import (
    DocumentNode,
    FieldNode,
    FragmentDefinitionNode,
    FragmentSpreadNode,
    InlineFragmentNode,
    NamedTypeNode,
    NameNode,
    OperationDefinitionNode,
    SelectionNode,
    SelectionSetNode,
    parse,
    print_ast,
)

from utils.graphql_queries import load_query

ROOT = Path(__file__).resolve().parents[1]
QUERIES_DIR = ROOT / "queries"
FLAT_DIR = QUERIES_DIR / "flat"
GENERATED_HEADER = "# GENERATED by `uv run invoke flatten-queries` from {source}: edit the source, not this file.\n"


def flat_path(source: Path) -> Path:
    """Where the flattened copy of a source query under ``queries/`` is written."""
    return FLAT_DIR / source.resolve().relative_to(QUERIES_DIR)


def source_path(flat: Path) -> Path:
    """The source query a flattened copy was written from."""
    return QUERIES_DIR / flat.resolve().relative_to(FLAT_DIR)


class _Flattener:
    """Rewrites one operation; ``prefix`` makes the names of the fragments it keeps unique across files."""

    def __init__(self, fragments: dict[str, FragmentDefinitionNode], prefix: str) -> None:
        self.fragments = fragments
        self.prefix = prefix
        self.kept: list[FragmentDefinitionNode] = []

    def _parts(self, selection: SelectionNode) -> tuple[NamedTypeNode | None, SelectionSetNode, tuple]:
        """Type condition, body and directives of a spread or an inline fragment."""
        if isinstance(selection, FragmentSpreadNode):
            definition = self.fragments[selection.name.value]
            return definition.type_condition, definition.selection_set, tuple(selection.directives or ())
        assert isinstance(selection, InlineFragmentNode)
        return selection.type_condition, selection.selection_set, tuple(selection.directives or ())

    def _field(self, field: FieldNode, inner) -> FieldNode:
        return FieldNode(
            alias=field.alias,
            name=field.name,
            arguments=field.arguments,
            directives=field.directives,
            selection_set=inner(field.selection_set) if field.selection_set else None,
        )

    def field_level(self, selection_set: SelectionSetNode) -> SelectionSetNode:
        """A field's selections: a spread or inline fragment becomes an inline fragment (one level)."""
        out: list[SelectionNode] = []
        for selection in selection_set.selections:
            if isinstance(selection, FieldNode):
                out.append(self._field(selection, self.field_level))
                continue
            type_condition, body, directives = self._parts(selection)
            out.append(
                InlineFragmentNode(
                    type_condition=type_condition, directives=directives, selection_set=self.inside_inline(body)
                )
            )
        return SelectionSetNode(selections=tuple(out))

    def inside_inline(self, selection_set: SelectionSetNode) -> SelectionSetNode:
        """An inline fragment's selections: a nested spread or inline fragment becomes a fragment used once."""
        out: list[SelectionNode] = []
        for selection in selection_set.selections:
            if isinstance(selection, FieldNode):
                out.append(self._field(selection, self.field_level))
                continue
            type_condition, body, directives = self._parts(selection)
            name = f"{self.prefix}{len(self.kept) + 1}"
            self.kept.append(
                FragmentDefinitionNode(
                    name=NameNode(value=name), type_condition=type_condition, selection_set=self.nested(body)
                )
            )
            out.append(FragmentSpreadNode(name=NameNode(value=name), directives=directives))
        return SelectionSetNode(selections=tuple(out))

    def nested(self, selection_set: SelectionSetNode) -> SelectionSetNode:
        """A kept fragment's body: every spread written out as an inline fragment, at any depth."""
        out: list[SelectionNode] = []
        for selection in selection_set.selections:
            if isinstance(selection, FieldNode):
                out.append(self._field(selection, self.nested))
                continue
            type_condition, body, directives = self._parts(selection)
            out.append(
                InlineFragmentNode(
                    type_condition=type_condition, directives=directives, selection_set=self.nested(body)
                )
            )
        return SelectionSetNode(selections=tuple(out))


def flatten_query(text: str, prefix: str) -> str:
    """The query document ``text`` (one operation and every fragment it spreads) with its fragments written out.

    ``prefix`` names the fragments that stay (``<prefix>1``, ``<prefix>2``, ...); give each query its own.
    """
    document = parse(text)
    fragments = {d.name.value: d for d in document.definitions if isinstance(d, FragmentDefinitionNode)}
    operations = [d for d in document.definitions if isinstance(d, OperationDefinitionNode)]
    if len(operations) != 1:
        raise ValueError(f"expected one operation, found {len(operations)}")
    operation = operations[0]
    flattener = _Flattener(fragments, prefix)
    flat_operation = OperationDefinitionNode(
        operation=operation.operation,
        name=operation.name,
        variable_definitions=operation.variable_definitions,
        directives=operation.directives,
        selection_set=flattener.field_level(operation.selection_set),
    )
    return print_ast(DocumentNode(definitions=(flat_operation, *flattener.kept))) + "\n"


def fragment_prefix(name: str) -> str:
    """The prefix of the fragments a registered query keeps: its name, so names never clash across files."""
    return f"{name}__F"


def load_flat_query(path: Path) -> str:
    """A query file with its shared fragments, flattened: for a query the code executes itself."""
    return flatten_query(load_query(path), fragment_prefix(path.stem))


def render_flat(name: str, source: Path) -> str:
    """The content of the registered, flattened copy of the source query ``source`` registered as ``name``."""
    relative = source.resolve().relative_to(ROOT).as_posix()
    return GENERATED_HEADER.format(source=relative) + flatten_query(load_query(source), fragment_prefix(name))


def registered_queries() -> list[tuple[str, Path, Path]]:
    """(name, registered flat copy, source) of every ``queries:`` entry of ``.infrahub.yml``.

    An entry must register the flat copy: a source path there would send the server the slow, fragment-built form.
    """
    import yaml  # noqa: PLC0415 - only the registry readers need it

    entries = yaml.safe_load((ROOT / ".infrahub.yml").read_text())["queries"]
    out = []
    for entry in entries:
        registered = ROOT / entry["file_path"]
        if FLAT_DIR not in registered.resolve().parents:
            raise ValueError(
                f"query {entry['name']} registers {entry['file_path']}: register its flat copy "
                f"{flat_path(registered).relative_to(ROOT).as_posix()} (uv run invoke flatten-queries)"
            )
        out.append((entry["name"], registered, source_path(registered)))
    return out


def write_flat_queries() -> list[Path]:
    """Write the flat copy of every registered query and delete copies nothing registers; returns what changed."""
    changed: list[Path] = []
    wanted: set[Path] = set()
    for name, registered, source in registered_queries():
        content = render_flat(name, source)
        wanted.add(registered.resolve())
        if not registered.is_file() or registered.read_text() != content:
            registered.parent.mkdir(parents=True, exist_ok=True)
            registered.write_text(content)
            changed.append(registered)
    for stale in sorted(FLAT_DIR.rglob("*.gql")):
        if stale.resolve() not in wanted:
            stale.unlink()
            changed.append(stale)
    return changed
